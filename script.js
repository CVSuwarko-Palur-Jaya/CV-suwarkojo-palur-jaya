const grid = document.querySelector("#article-grid");
const searchInput = document.querySelector("#search-input");
const emptyState = document.querySelector("#empty-state");
const categoryButtons = [...document.querySelectorAll(".category-chip")];
const dialog = document.querySelector("#article-dialog");
const dialogContent = document.querySelector("#dialog-content");
let activeCategory = "Semua";

function renderArticles() {
  const query = searchInput.value.trim().toLocaleLowerCase("id");
  const visibleArticles = articles
    .map((article, index) => ({ ...article, index }))
    .filter(article => (activeCategory === "Semua" || article.category === activeCategory)
      && `${article.title} ${article.category} ${article.excerpt}`.toLocaleLowerCase("id").includes(query));

  grid.innerHTML = visibleArticles.map(article => `
    <article class="article-card">
      <div class="card-image-wrap">
        <img class="card-image" src="${article.image}" alt="${article.alt}" loading="lazy">
      </div>
      <div class="card-topline"><span class="category-label">${article.category}</span><span>${article.date} &nbsp;·&nbsp; ${article.readTime}</span></div>
      <h3>${article.title}</h3>
      <p>${article.excerpt}</p>
      <button class="card-read article-open" data-article="${article.index}">Baca selengkapnya <span aria-hidden="true">↗</span></button>
    </article>
  `).join("");
  emptyState.hidden = visibleArticles.length !== 0;
}

function openArticle(index) {
  const article = articles[index];
  if (!article) return;
  dialogContent.innerHTML = `
    <div class="article-meta"><span class="category-label">${article.category}</span><span>•</span><span>${article.date}</span><span>•</span><span>${article.readTime}</span></div>
    <h2 id="dialog-title">${article.title}</h2>
    <img class="dialog-image" src="${article.image}" alt="${article.alt}">
    <p><strong>${article.excerpt}</strong></p>
    ${article.body.map(paragraph => `<p>${paragraph}</p>`).join("")}
    <p>— Redaksi Suwarko Jo</p>
  `;
  dialog.showModal();
}

categoryButtons.forEach(button => {
  button.addEventListener("click", () => {
    activeCategory = button.dataset.category;
    categoryButtons.forEach(item => item.classList.toggle("selected", item === button));
    renderArticles();
  });
});

searchInput.addEventListener("input", renderArticles);
document.addEventListener("click", event => {
  const articleButton = event.target.closest(".article-open");
  if (articleButton) openArticle(Number(articleButton.dataset.article));
});
document.querySelector(".dialog-close").addEventListener("click", () => dialog.close());
dialog.addEventListener("click", event => {
  if (event.target === dialog) dialog.close();
});
document.addEventListener("keydown", event => {
  if (event.key === "/" && !["INPUT", "TEXTAREA"].includes(document.activeElement.tagName)) {
    event.preventDefault();
    searchInput.focus();
  }
});

renderArticles();
